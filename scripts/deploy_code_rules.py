"""Compile admitted service-level Go function bodies into PW_Scanner/lib/fingerprint/code_rules.go. Regenerate the source registry, format it and verify compilation."""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import config  # noqa: E402
from fingerprint.agent.generated_rules.hand_code_rules import hand_code_rules  # noqa: E402
from services_config import IDENTIFICATION_CLUSTER_MEMBERS  # noqa: E402

REPO = Path(config.BASE_DIR)
ZGRAB2 = REPO / "PW_Scanner"
OUT = ZGRAB2 / "lib" / "fingerprint" / "code_rules.go"

_FORBIDDEN = [
    (re.compile(r"\bimport\b"), "import"),
    (re.compile(r"\bfor\s*\{"), "unbounded for loop"),
    (re.compile(r"\bgo\s+[\w(]"), "goroutine statement"),
]

_HEADER = """// Code generated by scripts/deploy_code_rules.py. DO NOT EDIT.
//
// Response identification and coverage validation.
// Response identification and coverage validation.
// Response identification and coverage validation.
// Response identification and coverage validation.

package fingerprint

import (
	"bytes"
	"encoding/binary"
)

// Response identification and coverage validation.
var (
	_ = bytes.Compare
	_ = binary.BigEndian
)

// Response identification and coverage validation.
type codeRuleEntry struct {
	Service string
	Source  string
	Fn      func([]byte) bool
}
"""

_FOOTER = """
// Response identification and coverage validation.
// Response identification and coverage validation.
var identificationCandidateGroups = map[string][]string{
{IDENTIFICATION_GROUPS}
}

// Response identification and coverage validation.
func IdentificationCandidates(service string) []string {
	if service == "" {
		return nil
	}
	if group, ok := identificationCandidateGroups[service]; ok {
		return append([]string(nil), group...)
	}
	return []string{service}
}

// Response identification and coverage validation.
// Response identification and coverage validation.
func MatchAllCode(resp []byte) []MatchInfo {
	var out []MatchInfo
	for _, e := range codeRuleEntries {
		if e.Fn(resp) {
			out = append(out, MatchInfo{Service: e.Service, Source: e.Source, Tier: TierOf(e.Source)})
		}
	}
	return out
}
"""

def _sanitize_ident(s: str) -> str:
    return re.sub(r"[^0-9A-Za-z_]", "_", s)

def _check_body(body: str, origin: str) -> None:
    for pat, name in _FORBIDDEN:
        if pat.search(body):
            raise ValueError(f"[{origin}] body contains a forbidden construct ({name}):\n{body}")

def _indent(body: str) -> str:
    """Indent generated Go body lines consistently."""
    return "\n".join("\t" + ln if ln.strip() else ln for ln in body.splitlines())

def _parse_args(argv=None):
    p = argparse.ArgumentParser(
        description="Generate the compiled service-code registry.")
    p.add_argument("--input", default=config.RULE_GEN_OUTPUT,
                   help="Service rules JSON with type=code entries (default: config.RULE_GEN_OUTPUT)")
    p.add_argument("--output", default=str(OUT),
                   help="Output code_rules.go path")
    p.add_argument("--zgrab-dir", default=str(ZGRAB2),
                   help="Go build working directory (default: PW_Scanner)")
    p.add_argument("--no-hand-code", action="store_true",
                   help="Exclude built-in hand-written fallback code rules")
    return p.parse_args(argv)

def load_rules(input_path=None, include_hand=True):
    """Load rules."""
    path = Path(input_path) if input_path is not None else Path(config.RULE_GEN_OUTPUT)
    if not path.exists():
        raise ValueError(f"[error] input does not exist: {path}")
    try:
        cr = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        raise ValueError(f"[error] {path} parsing failed: {e}") from e
    if not isinstance(cr, list):
        raise ValueError(f"[error] {path} must be a top-level JSON array; got {type(cr).__name__}")
    out = []
    for i, r in enumerate(cr):
        if not isinstance(r, dict):
            raise ValueError(f"[error] {path} entry {i} is not a JSON object: {r!r}")
        if r.get("type") != "code":
            continue
        service = r.get("service")
        code = r.get("code")
        if (not isinstance(service, str) or not service.strip()
                or not isinstance(code, str) or not code.strip()):
            raise ValueError(f"[error] {path} entry {i} code entry is missing service/code: {r!r}")
        out.append((service, "code", code, f"agent:{service}"))
    if include_hand:
        
        for r in hand_code_rules():
            out.append((r["service"], "hand_code", r["code"], f"hand:{r['family']}/{r['service']}"))
    return out

def render(rules):
    funcs = []
    entries = []
    counter = {}  # (source,cluster) -> idx
    for service, source, code, origin in rules:
        _check_body(code, origin)
        key = (source, service)
        idx = counter.get(key, 0)
        counter[key] = idx + 1
        fname = f"codeMatch_{_sanitize_ident(source)}_{_sanitize_ident(service)}_{idx}"
        funcs.append(
            f"// {origin}\n"
            f"func {fname}(resp []byte) (r bool) {{\n"
            f"\tdefer func() {{ recover() }}()\n"
            f"{_indent(code)}\n"
            f"}}"
        )
        entries.append(f'\t{{Service: "{service}", Source: "{source}", Fn: {fname}}},')

    group_lines = []
    for canonical, candidates in sorted(IDENTIFICATION_CLUSTER_MEMBERS.items()):
        if len(candidates) <= 1:
            continue
        quoted = ", ".join(json.dumps(name) for name in candidates)

        for alias in [canonical, *candidates]:
            group_lines.append(
                f'\t{json.dumps(alias)}: []string{{{quoted}}},')
    footer = _FOOTER.replace("{IDENTIFICATION_GROUPS}", "\n".join(group_lines))
    body = _HEADER + "\n" + "\n\n".join(funcs) + "\n\nvar codeRuleEntries = []codeRuleEntry{\n" + \
        "\n".join(entries) + "\n}\n" + footer
    return body

def main(argv=None):
    args = _parse_args(argv)
    try:
        rules = load_rules(input_path=args.input, include_hand=not args.no_hand_code)
        if not rules:
            print("[error] no code rules to generate", file=sys.stderr)
            return 1
        src = render(rules)
    except ValueError as e:
        print(e, file=sys.stderr)
        return 1
    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(src, encoding="utf-8")
    n_agent = sum(1 for _, s, _, _ in rules if s == "code")
    n_hand = sum(1 for _, s, _, _ in rules if s == "hand_code")
    clusters = sorted({svc for svc, _, _, _ in rules})
    print(f"[gen] {len(rules)} code rules (agent code={n_agent}, hand_code={n_hand})，"
          f"{len(clusters)} cluster → {out_path}")

    f = subprocess.run(["gofmt", "-w", str(out_path)])
    if f.returncode != 0:
        print("[warn] gofmt failed; continuing", file=sys.stderr)

    r = subprocess.run(["go", "build", "./lib/fingerprint/"], cwd=str(args.zgrab_dir),
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(f"[error] fingerprint package build failed:\n{r.stderr}", file=sys.stderr)
        return 1
    print("[ok] fingerprint package build passed")
    return 0

if __name__ == "__main__":
    sys.exit(main())
