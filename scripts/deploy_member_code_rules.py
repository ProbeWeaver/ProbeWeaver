"""Compile admitted implementation-level Go bodies into PW_Scanner/lib/fingerprint/member_code_rules.go. These rules run only inside a confirmed service."""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import config  # noqa: E402

REPO = Path(config.BASE_DIR)
ZGRAB2 = REPO / "PW_Scanner"
IN = Path(config.MEMBER_RULES_OUTPUT)  # PW_Scanner/member_rules.json
OUT = ZGRAB2 / "lib" / "fingerprint" / "member_code_rules.go"

_FORBIDDEN = [
    (re.compile(r"\bimport\b"), "import"),
    (re.compile(r"\bfor\s*\{"), "unbounded for loop"),
    (re.compile(r"\bgo\s+[\w(]"), "goroutine statement"),
]

_HEADER = """// Code generated by scripts/deploy_member_code_rules.py. DO NOT EDIT.
//
// Response identification and coverage validation.
// Response identification and coverage validation.
// Response identification and coverage validation.
// Response identification and coverage validation.

package fingerprint

import (
\t"bytes"
\t"encoding/binary"
)

// Response identification and coverage validation.
var (
\t_ = bytes.Compare
\t_ = binary.BigEndian
)

// Response identification and coverage validation.
type memberCodeEntry struct {
\tCluster string
\tMember  string
\tFn      func([]byte) bool
}
"""

_FOOTER = """
// Response identification and coverage validation.
// Response identification and coverage validation.
// Response identification and coverage validation.
func MemberResolveCode(cluster string, resp []byte) (member string, ok bool) {
\tfor _, e := range memberCodeEntries {
\t\tif e.Cluster == cluster && e.Fn(resp) {
\t\t\treturn e.Member, true
\t\t}
\t}
\treturn "", false
}
"""

def _sanitize_ident(s: str) -> str:
    return re.sub(r"[^0-9A-Za-z_]", "_", s)

def _check_body(body: str, origin: str) -> None:
    for pat, name in _FORBIDDEN:
        if pat.search(body):
            raise ValueError(f"[{origin}] body contains a forbidden construct ({name}):\n{body}")

def _indent(body: str) -> str:
    return "\n".join("\t" + ln if ln.strip() else ln for ln in body.splitlines())

def _parse_args(argv=None):
    p = argparse.ArgumentParser(
        description="Generate the compiled implementation-code registry.")
    p.add_argument("--input", default=str(IN),
                   help="Implementation rules JSON with type=member_code entries")
    p.add_argument("--output", default=str(OUT),
                   help="Output member_code_rules.go path")
    p.add_argument("--zgrab-dir", default=str(ZGRAB2),
                   help="Go build working directory (default: PW_Scanner)")
    return p.parse_args(argv)

def load_rules(input_path=None):
    """Load rules."""
    path = Path(input_path) if input_path is not None else IN
    if not path.exists():
        return []
    try:
        rules = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        raise ValueError(f"[error] {path} parsing failed: {e}") from e
    if not isinstance(rules, list):
        raise ValueError(f"[error] {path} must be a top-level JSON array; got {type(rules).__name__}")
    out = []
    for i, r in enumerate(rules):
        if not isinstance(r, dict):
            raise ValueError(f"[error] {path} entry {i} is not a JSON object: {r!r}")
        if r.get("type") != "member_code":
            continue
        code = r.get("code")
        member = r.get("member")
        cluster = r.get("service")
        if (not isinstance(code, str) or not code.strip()
                or not isinstance(member, str) or not member.strip()
                or not isinstance(cluster, str) or not cluster.strip()):
            raise ValueError(
                f"[error] {path} entry {i} member_code entry is missing service/member/code: {r!r}")
        out.append((cluster, member, code, f"member:{cluster}/{member}"))
    return out

def render(rules):
    funcs = []
    entries = []
    counter = {}  # (cluster,member) -> idx
    for cluster, member, code, origin in rules:
        _check_body(code, origin)
        key = (cluster, member)
        idx = counter.get(key, 0)
        counter[key] = idx + 1
        fname = f"memberMatch_{_sanitize_ident(cluster)}_{_sanitize_ident(member)}_{idx}"
        funcs.append(
            f"// {origin}\n"
            f"func {fname}(resp []byte) (r bool) {{\n"
            f"\tdefer func() {{ recover() }}()\n"
            f"{_indent(code)}\n"
            f"}}"
        )
        entries.append(f'\t{{Cluster: "{cluster}", Member: "{member}", Fn: {fname}}},')

    body = _HEADER + "\n" + "\n\n".join(funcs)
    if funcs:
        body += "\n\n"
    body += "var memberCodeEntries = []memberCodeEntry{\n" + "\n".join(entries) + "\n}\n" + _FOOTER
    return body

def main(argv=None):
    args = _parse_args(argv)
    try:
        rules = load_rules(input_path=args.input)
        src = render(rules)
    except ValueError as e:
        print(e, file=sys.stderr)
        return 1
    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(src, encoding="utf-8")
    clusters = sorted({c for c, _, _, _ in rules})
    print(f"[gen] {len(rules)} implementation code rules; {len(clusters)} cluster → {out_path}")

    f = subprocess.run(["gofmt", "-w", str(out_path)])
    if f.returncode != 0:
        print("[warn] gofmt failed; continuing", file=sys.stderr)

    r = subprocess.run(["go", "build", "./lib/fingerprint/"], cwd=str(args.zgrab_dir),
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(f"[error] fingerprint package build failed:\n{r.stderr}", file=sys.stderr)
        return 1
    print("[ok] fingerprint package build passed")
    return 0

if __name__ == "__main__":
    sys.exit(main())
