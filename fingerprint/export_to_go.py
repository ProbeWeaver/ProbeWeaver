"""
Export trained model to Go source code using m2cgen.

Generates pure Go if/else code with zero runtime dependencies,
suitable for embedding in ZGrab2 custom module.
"""

import json
import argparse
import logging
import re
from pathlib import Path

import joblib

logger = logging.getLogger(__name__)

def export_go(
    model_dir: str = "fingerprint_model_output",
    output_path: str = None,
    package_name: str = "fingerprint",
    function_name: str = "PredictService",
):
    """
    Export trained RandomForest to Go source code.

    Args:
        model_dir: Directory containing saved model artifacts
        output_path: Output Go file path (default: model_dir/fingerprint_model.go)
        package_name: Go package name
        function_name: Go function name for prediction
    """
    try:
        import m2cgen as m2c
    except ImportError:
        raise ImportError(
            "m2cgen is not installed in the protocol_fuzzer environment; "
            "install it there before exporting the model"
        )

    model_dir = Path(model_dir)
    if output_path is None:
        output_path = model_dir / "fingerprint_model.go"
    output_path = Path(output_path)

    # Load model and metadata
    model = joblib.load(model_dir / "fingerprint_model.joblib")
    label_encoder = joblib.load(model_dir / "label_encoder.joblib")

    meta_path = model_dir / "training_meta.json"
    if meta_path.exists():
        with open(meta_path, "r") as f:
            meta = json.load(f)
        feature_names = meta.get("feature_names", [])
        # Legacy trainers stored classes at the top level.  The tamper-evident
        # Tier-2 artifact keeps them under data; support both without falling
        # back to an empty runtime label registry.
        classes = meta.get("classes") or (
            meta.get("data", {}).get("classes") if isinstance(
                meta.get("data"), dict) else None)
        classes = classes or list(label_encoder.classes_)
    else:
        classes = list(label_encoder.classes_)
        feature_names = []

    # Generate Go code
    go_code = m2c.export_to_go(model)

    # Build final file with header and label mapping
    label_map = {i: cls for i, cls in enumerate(classes)}

    header = f'''// Code generated by m2cgen. DO NOT EDIT.
// Trained with RandomForestClassifier ({model.n_estimators} trees, max_depth={model.max_depth})
// {len(classes)} classes: {", ".join(classes)}
// {len(feature_names)} features: {", ".join(feature_names)}

package {package_name}

// PredictServiceLabel maps prediction index to service name.
// Generated from label encoder classes.
var PredictServiceLabel = map[int]string{{\n'''

    for idx, cls in label_map.items():
        header += f'\t{idx}: "{cls}",\n'

    header += "}\n\n"

    # Add wrapper function for convenience
    wrapper = f'''
// PredictService takes feature values and returns the predicted service name.
func {function_name}(features []float64) string {{
	proba := score(rfInput(features))
	idx := 0
	best := proba[0]
	for i := 1; i < len(proba); i++ {{
		if proba[i] > best {{
			best = proba[i]
			idx = i
		}}
	}}
	if label, ok := PredictServiceLabel[idx]; ok {{
		return label
	}}
	return "unknown"
}}

// PredictionResult holds the prediction output with confidence information.
type PredictionResult struct {{
	Service    string  `json:"service"`
	Confidence float64 `json:"confidence"`
	IsReliable bool    `json:"is_reliable"`
}}

// PredictServiceWithConfidence returns the predicted service with confidence score.
// The confidence is the max probability from the RandomForest vote distribution.
// confidenceThreshold: predictions below this value are marked as unreliable (use 0.0 to accept all).
func PredictServiceWithConfidence(features []float64, confidenceThreshold float64) PredictionResult {{
	proba := score(rfInput(features))

	bestIdx := 0
	bestProba := proba[0]
	for i := 1; i < len(proba); i++ {{
		if proba[i] > bestProba {{
			bestProba = proba[i]
			bestIdx = i
		}}
	}}

	service := "unknown"
	if label, ok := PredictServiceLabel[bestIdx]; ok {{
		service = label
	}}

	reliable := bestProba >= confidenceThreshold
	if !reliable {{
		service = "unknown"
	}}

	return PredictionResult{{
		Service:    service,
		Confidence: bestProba,
		IsReliable: reliable,
	}}
}}
'''

    # Write output
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(header)
        f.write(go_code)
        f.write(wrapper)

    logger.info(f"Go model exported to {output_path}")
    logger.info(f"  {len(classes)} classes, {len(feature_names)} features")
    logger.info(f"  File size: {output_path.stat().st_size / 1024:.1f} KB")

    # Also export feature extraction helper
    _export_feature_extractor(output_path.parent, feature_names, function_name)

    return str(output_path)

def export_member_models_go(
    member_model_dir: str,
    output_path: str = None,
    package_name: str = "fingerprint",
):
    """Export implementation RFs with exactly the shared Go feature order."""
    try:
        import m2cgen as m2c
    except ImportError:
        raise ImportError(
            "m2cgen is not installed in the protocol_fuzzer environment; "
            "install it there before exporting member models"
        )

    member_model_dir = Path(member_model_dir)
    manifest_path = member_model_dir / "manifest.json"
    if not manifest_path.exists():
        raise FileNotFoundError(f"missing manifest.json: {manifest_path} (run scripts/train_member_rf_corpus.py first)")
    with open(manifest_path, "r", encoding="utf-8") as f:
        manifest = json.load(f)
    ok_clusters = sorted(c for c, m in manifest.items() if m.get("status") == "ok")
    if not ok_clusters:
        logger.warning("No status=ok services in manifest; exporting an empty member registry")

    if output_path is None:
        output_path = member_model_dir / "member_models.go"
    output_path = Path(output_path)

    score_fns = []
    label_maps = []
    feat_ref = None
    for cluster in ok_clusters:
        cdir = member_model_dir / cluster
        model = joblib.load(cdir / "model.joblib")
        le = joblib.load(cdir / "label_encoder.joblib")
        with open(cdir / "training_meta.json", "r", encoding="utf-8") as f:
            meta = json.load(f)
        
        if feat_ref is None:
            feat_ref = meta["feature_names"]
        elif meta["feature_names"] != feat_ref:
            raise ValueError(f"{cluster} feature order differs from the first service; Go inference would be misaligned")

        go = m2c.export_to_go(model)

        for sym in ("score", "addVectors", "mulVectorNumber"):
            go = re.sub(rf"\b{sym}\b", f"{sym}_{cluster}", go)
        score_fns.append(go.strip())

        members = list(le.classes_)
        map_lines = "\n".join(f'\t{i}: "{m}",' for i, m in enumerate(members))
        label_maps.append(f'var memberLabel_{cluster} = map[int]string{{\n{map_lines}\n}}')

    cases = "\n".join(
        f'\tcase "{c}": return memberPredict(score_{c}(features), memberLabel_{c}, threshold)'
        for c in ok_clusters
    )
    header = f'''// Code generated by export_member_models_go. DO NOT EDIT.
// Per-service implementation RandomForest.
// {len(ok_clusters)} services have implementation models; shared feature order ({len(feat_ref or [])} features).

package {package_name}

// MemberPredictionResult holds a member (implementation) prediction with confidence.
type MemberPredictionResult struct {{
	Member     string  `json:"member"`
	Confidence float64 `json:"confidence"`
	IsReliable bool    `json:"is_reliable"`
}}

// Response identification and coverage validation.
func memberPredict(proba []float64, labels map[int]string, threshold float64) MemberPredictionResult {{
	if len(proba) == 0 {{
		return MemberPredictionResult{{Member: "unknown"}}
	}}
	bestIdx := 0
	best := proba[0]
	for i := 1; i < len(proba); i++ {{
		if proba[i] > best {{
			best = proba[i]
			bestIdx = i
		}}
	}}
	member := "unknown"
	if lbl, ok := labels[bestIdx]; ok {{
		member = lbl
	}}
	reliable := best >= threshold
	if !reliable {{
		member = "unknown"
	}}
	return MemberPredictionResult{{Member: member, Confidence: best, IsReliable: reliable}}
}}

// PredictMember runs the per-cluster member RF for the given cluster.
// Response identification and coverage validation.
func PredictMember(cluster string, features []float64, threshold float64) MemberPredictionResult {{
	features = rfInput(features)
	switch cluster {{
{cases}
	}}
	return MemberPredictionResult{{Member: "unknown"}}
}}

'''

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(header)
        f.write("\n".join(label_maps))
        f.write("\n\n")
        f.write("\n\n".join(score_fns))
        f.write("\n")

    logger.info(f"Member models exported to {output_path} ({len(ok_clusters)} clusters)")
    logger.info(f"  clusters: {', '.join(ok_clusters) if ok_clusters else '(none)'}")
    return str(output_path)

def _export_feature_extractor(output_dir: Path, feature_names: list, fn_name: str):
    """Generate Go helper for extracting features from request + response bytes."""

    has_request = any(n.startswith("req_") for n in feature_names)
    has_relationship = any(n.startswith("req_resp_") or n == "resp_shorter_than_req" for n in feature_names)

    name_to_idx = {name: i for i, name in enumerate(feature_names)}
    n_features = len(feature_names)

    code = f'''// Code generated by fingerprint exporter. DO NOT EDIT.

package fingerprint

import (
	"math"
)

// FeatureNames is the ordered list of feature names matching the training data.
var FeatureNames = []string{{{', '.join(json.dumps(name) for name in feature_names)}}}

// sklearn trees convert prediction inputs to float32 before comparing their
// float64 split thresholds. Match that conversion in exported Go models.
func rfInput(features []float64) []float64 {{
	result := make([]float64, len(features))
	for i, value := range features {{ result[i] = float64(float32(value)) }}
	return result
}}

// ExtractFeatures extracts {n_features} features from response bytes (Approach A, 30 features).
func ExtractFeatures(resp []byte) []float64 {{
	features := make([]float64, {n_features})
	n := len(resp)
'''

    code += _go_response_features(name_to_idx, n_features)

    if has_request:
        code += f'''

// ExtractFeaturesWithContext extracts {n_features} features from request + response bytes
// (Approach C, 44 features including request and relationship features).
func ExtractFeaturesWithContext(req []byte, resp []byte) []float64 {{
	features := ExtractFeatures(resp)
'''
        code += _go_request_features(name_to_idx)
        code += _go_relationship_features(name_to_idx)
        code += '\treturn features\n}\n'

    # Helper functions
    code += '''
func shannonEntropy(byteVals []float64) float64 {
	counts := make(map[float64]int)
	for _, v := range byteVals { counts[v]++ }
	total := float64(len(byteVals))
	entropy := 0.0
	for _, c := range counts {
		p := float64(c) / total
		if p > 0 { entropy -= p * math.Log2(p) }
	}
	return entropy
}

func shannonEntropyBytes(data []byte) float64 {
	if len(data) == 0 { return 0.0 }
	counts := make(map[uint8]int)
	for _, b := range data { counts[b]++ }
	total := float64(len(data))
	entropy := 0.0
	for _, c := range counts {
		p := float64(c) / total
		if p > 0 { entropy -= p * math.Log2(p) }
	}
	return entropy
}

func meanF(vals []float64) float64 {
	if len(vals) == 0 { return 0 }
	s := 0.0
	for _, v := range vals { s += v }
	return s / float64(len(vals))
}

func stdDevF(vals []float64) float64 {
	if len(vals) < 2 { return 0 }
	m := meanF(vals)
	variance := 0.0
	for _, v := range vals { variance += (v - m) * (v - m) }
	return math.Sqrt(variance / float64(len(vals)))
}

func medianF(vals []float64) float64 {
	sorted := make([]float64, len(vals))
	copy(sorted, vals)
	sortFloat64s(sorted)
	n := len(sorted)
	if n%2 == 0 { return (sorted[n/2-1] + sorted[n/2]) / 2 }
	return sorted[n/2]
}

func sortFloat64s(a []float64) {
	for i := 1; i < len(a); i++ {
		for j := i; j > 0 && a[j] < a[j-1]; j-- {
			a[j], a[j-1] = a[j-1], a[j]
		}
	}
}

func uniqueByteCount(data []byte) int {
	s := make(map[uint8]struct{})
	for _, b := range data { s[b] = struct{}{} }
	return len(s)
}
'''

    helper_path = output_dir / "feature_extractor.go"
    with open(helper_path, "w", encoding="utf-8") as f:
        f.write(code)

    logger.info(f"Feature extractor helper saved to {helper_path}")

def _go_response_features(name_to_idx: dict, n_features: int) -> str:
    """Generate Go code for response feature extraction."""
    idx = name_to_idx
    code = ''

    if "resp_len" in idx:
        code += f'\tfeatures[{idx["resp_len"]}] = float64(n) // resp_len\n'

    code += '''
	if n > 0 {
		byteVals := make([]float64, n)
		for i, b := range resp {
			byteVals[i] = float64(b)
		}
'''
    if "resp_entropy" in idx:
        code += f'\t\tfeatures[{idx["resp_entropy"]}] = shannonEntropy(byteVals)  // resp_entropy\n'
    if "resp_byte_mean" in idx:
        code += f'\t\tfeatures[{idx["resp_byte_mean"]}] = meanF(byteVals)  // resp_byte_mean\n'
    if "resp_byte_std" in idx:
        code += f'\t\tfeatures[{idx["resp_byte_std"]}] = stdDevF(byteVals)  // resp_byte_std\n'
    if "resp_byte_median" in idx:
        code += f'\t\tfeatures[{idx["resp_byte_median"]}] = medianF(byteVals)  // resp_byte_median\n'
    if "resp_n_unique_bytes" in idx:
        code += f'\t\tfeatures[{idx["resp_n_unique_bytes"]}] = float64(uniqueByteCount(resp))  // resp_n_unique_bytes\n'

    code += '\t}\n'

    # Header features
    if "resp_first_byte" in idx:
        code += f'\tif n >= 1 {{ features[{idx["resp_first_byte"]}] = float64(resp[0]) }}  // resp_first_byte\n'
    if "resp_first_2_bytes" in idx:
        code += f'\tif n >= 2 {{ features[{idx["resp_first_2_bytes"]}] = float64(uint16(resp[0])<<8 | uint16(resp[1])) }}  // resp_first_2_bytes\n'
    if "resp_first_4_bytes" in idx:
        code += f'\tif n >= 4 {{ features[{idx["resp_first_4_bytes"]}] = float64(uint32(resp[0])<<24 | uint32(resp[1])<<16 | uint32(resp[2])<<8 | uint32(resp[3])) }}  // resp_first_4_bytes\n'
    if "resp_byte_at_6" in idx:
        code += f'\tif n >= 7 {{ features[{idx["resp_byte_at_6"]}] = float64(resp[6]) }}  // resp_byte_at_6\n'
    if "resp_byte_at_8" in idx:
        code += f'\tif n >= 9 {{ features[{idx["resp_byte_at_8"]}] = float64(resp[8]) }}  // resp_byte_at_8\n'
    if "resp_byte_at_12" in idx:
        code += f'\tif n >= 13 {{ features[{idx["resp_byte_at_12"]}] = float64(resp[12]) }}  // resp_byte_at_12\n'

    # Tail features
    if "resp_last_byte" in idx:
        code += f'\tif n >= 1 {{ features[{idx["resp_last_byte"]}] = float64(resp[n-1]) }}  // resp_last_byte\n'
    if "resp_last_2_bytes" in idx:
        code += f'\tif n >= 2 {{ features[{idx["resp_last_2_bytes"]}] = float64(uint16(resp[n-2])<<8 | uint16(resp[n-1])) }}  // resp_last_2_bytes\n'
    if "resp_last_4_bytes" in idx:
        code += f'\tif n >= 4 {{ features[{idx["resp_last_4_bytes"]}] = float64(uint32(resp[n-4])<<24 | uint32(resp[n-3])<<16 | uint32(resp[n-2])<<8 | uint32(resp[n-1])) }}  // resp_last_4_bytes\n'

    # Character composition
    code += '\tif n > 0 {\n'
    code += '\t\tnullCount := 0\n\t\tprintableCount := 0\n\t\tisASCII := true\n\t\thasCRLF := false\n'
    code += '\t\thasNull := false\n\t\thasHighBytes := false\n\t\tletterCount := 0\n'
    code += '\t\tfor _, b := range resp {\n'
    code += '\t\t\tif b == 0 { nullCount++; hasNull = true }\n'
    code += '\t\t\tif b >= 0x20 && b <= 0x7E { printableCount++ }\n'
    code += '\t\t\tif (b < 0x20 || b > 0x7E) && b != 0x0A && b != 0x0D && b != 0x09 { isASCII = false }\n'
    code += '\t\t\tif b > 0x7F { hasHighBytes = true }\n'
    code += '\t\t\tif (b >= 0x41 && b <= 0x5A) || (b >= 0x61 && b <= 0x7A) { letterCount++ }\n'
    code += '\t\t}\n'
    code += '\t\tfor i := 0; i < n-1; i++ {\n'
    code += '\t\t\tif resp[i] == 0x0D && resp[i+1] == 0x0A { hasCRLF = true; break }\n'
    code += '\t\t}\n'

    if "resp_null_ratio" in idx:
        code += f'\t\tfeatures[{idx["resp_null_ratio"]}] = float64(nullCount) / float64(n)  // resp_null_ratio\n'
    if "resp_printable_ratio" in idx:
        code += f'\t\tfeatures[{idx["resp_printable_ratio"]}] = float64(printableCount) / float64(n)  // resp_printable_ratio\n'
    if "resp_is_ascii" in idx:
        code += f'\t\tif isASCII {{ features[{idx["resp_is_ascii"]}] = 1.0 }} else {{ features[{idx["resp_is_ascii"]}] = 0.0 }}  // resp_is_ascii\n'
    if "resp_has_crlf" in idx:
        code += f'\t\tif hasCRLF {{ features[{idx["resp_has_crlf"]}] = 1.0 }} else {{ features[{idx["resp_has_crlf"]}] = 0.0 }}  // resp_has_crlf\n'
    if "resp_has_null" in idx:
        code += f'\t\tif hasNull {{ features[{idx["resp_has_null"]}] = 1.0 }} else {{ features[{idx["resp_has_null"]}] = 0.0 }}  // resp_has_null\n'
    if "resp_has_high_bytes" in idx:
        code += f'\t\tif hasHighBytes {{ features[{idx["resp_has_high_bytes"]}] = 1.0 }} else {{ features[{idx["resp_has_high_bytes"]}] = 0.0 }}  // resp_has_high_bytes\n'
    if "resp_letter_ratio" in idx:
        code += f'\t\tfeatures[{idx["resp_letter_ratio"]}] = float64(letterCount) / float64(n)  // resp_letter_ratio\n'
    code += '\t}\n'

    # Structural features
    code += '\tif n > 0 {\n'
    code += '\t\tmaxRun := 1\n\t\tcurRun := 1\n'
    code += '\t\tfor i := 1; i < n; i++ {\n'
    code += '\t\t\tif resp[i] == resp[i-1] { curRun++; if curRun > maxRun { maxRun = curRun } } else { curRun = 1 }\n'
    code += '\t\t}\n'
    if "resp_has_repeated_bytes" in idx:
        code += f'\t\tif maxRun >= 3 {{ features[{idx["resp_has_repeated_bytes"]}] = 1.0 }} else {{ features[{idx["resp_has_repeated_bytes"]}] = 0.0 }}  // resp_has_repeated_bytes\n'
    if "resp_max_run_length" in idx:
        code += f'\t\tfeatures[{idx["resp_max_run_length"]}] = float64(maxRun)  // resp_max_run_length\n'
    if "resp_len_mod_8" in idx:
        code += f'\t\tfeatures[{idx["resp_len_mod_8"]}] = float64(n % 8)  // resp_len_mod_8\n'
    if "resp_len_mod_16" in idx:
        code += f'\t\tfeatures[{idx["resp_len_mod_16"]}] = float64(n % 16)  // resp_len_mod_16\n'
    if "resp_is_power_of_2_len" in idx:
        code += f'\t\tif n > 0 && (n & (n-1)) == 0 {{ features[{idx["resp_is_power_of_2_len"]}] = 1.0 }} else {{ features[{idx["resp_is_power_of_2_len"]}] = 0.0 }}  // resp_is_power_of_2_len\n'
    code += '\t}\n'

    # N-gram features
    code += '\tif n >= 2 {\n'
    code += '\t\tgramCount := make(map[[2]uint8]int)\n'
    code += '\t\tfor i := 0; i < n-1; i++ { gramCount[[2]uint8{resp[i], resp[i+1]}]++ }\n'
    code += '\t\tmaxFreq := 0\n'
    code += '\t\tfor _, c := range gramCount { if c > maxFreq { maxFreq = c } }\n'
    if "resp_n_2grams" in idx:
        code += f'\t\tfeatures[{idx["resp_n_2grams"]}] = float64(len(gramCount))  // resp_n_2grams\n'
    if "resp_2gram_ratio" in idx:
        code += f'\t\tfeatures[{idx["resp_2gram_ratio"]}] = float64(len(gramCount)) / float64(n-1)  // resp_2gram_ratio\n'
    if "resp_most_common_2gram_freq" in idx:
        code += f'\t\tfeatures[{idx["resp_most_common_2gram_freq"]}] = float64(maxFreq) / float64(n-1)  // resp_most_common_2gram_freq\n'
    code += '\t}\n'

    code += '\treturn features\n}\n'
    return code

def _go_request_features(idx: dict) -> str:
    """Generate Go code for request feature extraction (7 features)."""
    code = '\treqLen := len(req)\n'
    code += '\treqN := len(req)\n'

    if "req_len" in idx:
        code += f'\tfeatures[{idx["req_len"]}] = float64(reqLen)  // req_len\n'
    if "req_entropy" in idx:
        code += f'\tfeatures[{idx["req_entropy"]}] = shannonEntropyBytes(req)  // req_entropy\n'
    if "req_first_byte" in idx:
        code += f'\tif reqN >= 1 {{ features[{idx["req_first_byte"]}] = float64(req[0]) }}  // req_first_byte\n'
    if "req_first_2_bytes" in idx:
        code += f'\tif reqN >= 2 {{ features[{idx["req_first_2_bytes"]}] = float64(uint16(req[0])<<8 | uint16(req[1])) }}  // req_first_2_bytes\n'
    if "req_first_4_bytes" in idx:
        code += f'\tif reqN >= 4 {{ features[{idx["req_first_4_bytes"]}] = float64(uint32(req[0])<<24 | uint32(req[1])<<16 | uint32(req[2])<<8 | uint32(req[3])) }}  // req_first_4_bytes\n'
    if "req_last_byte" in idx:
        code += f'\tif reqN >= 1 {{ features[{idx["req_last_byte"]}] = float64(req[reqN-1]) }}  // req_last_byte\n'
    if "req_last_2_bytes" in idx:
        code += f'\tif reqN >= 2 {{ features[{idx["req_last_2_bytes"]}] = float64(uint16(req[reqN-2])<<8 | uint16(req[reqN-1])) }}  // req_last_2_bytes\n'

    return code

def _go_relationship_features(idx: dict) -> str:
    """Generate Go code for relationship features (7 features)."""
    code = '\trespLen := len(resp)\n'

    if "req_resp_len_ratio" in idx:
        code += f'\t{{\n\t\trespLenOr1 := float64(respLen)\n\t\tif respLenOr1 < 1 {{ respLenOr1 = 1 }}\n'
        code += f'\t\tfeatures[{idx["req_resp_len_ratio"]}] = float64(reqLen) / respLenOr1  // req_resp_len_ratio\n'
        code += f'\t}}\n'
    if "req_resp_len_diff" in idx:
        code += '\t{{\n'
        code += f'\t\tdiff := reqLen - respLen\n'
        code += f'\t\tif diff < 0 {{ diff = -diff }}\n'
        code += f'\t\tfeatures[{idx["req_resp_len_diff"]}] = float64(diff)  // req_resp_len_diff\n'
        code += '\t}}\n'
    if "req_resp_entropy_diff" in idx:
        code += f'\t{{\n'
        code += f'\t\treqEnt := shannonEntropyBytes(req)\n'
        code += f'\t\trespEnt := features[{idx.get("resp_entropy", 1)}]  // resp_entropy\n'
        code += f'\t\tdiff := reqEnt - respEnt\n'
        code += f'\t\tif diff < 0 {{ diff = -diff }}\n'
        code += f'\t\tfeatures[{idx["req_resp_entropy_diff"]}] = diff  // req_resp_entropy_diff\n'
        code += f'\t}}\n'
    if "req_resp_first_byte_match" in idx:
        code += '\t{\n'
        code += f'\t\tif len(req) >= 1 && respLen >= 1 && req[0] == resp[0] {{\n'
        code += f'\t\t\tfeatures[{idx["req_resp_first_byte_match"]}] = 1.0\n'
        code += f'\t\t}} else {{\n'
        code += f'\t\t\tfeatures[{idx["req_resp_first_byte_match"]}] = 0.0\n'
        code += f'\t\t}}  // req_resp_first_byte_match\n'
        code += '\t}\n'
    if "req_resp_byte_mean_diff" in idx:
        code += '\t{\n'
        code += f'\t\treqMean := 0.0\n\t\tif reqLen > 0 {{ for _, b := range req {{ reqMean += float64(b) }}; reqMean /= float64(reqLen) }}\n'
        code += f'\t\trespMean := features[{idx.get("resp_byte_mean", 2)}]  // resp_byte_mean\n'
        code += f'\t\tdiff := reqMean - respMean\n'
        code += f'\t\tif diff < 0 {{ diff = -diff }}\n'
        code += f'\t\tfeatures[{idx["req_resp_byte_mean_diff"]}] = diff  // req_resp_byte_mean_diff\n'
        code += '\t}\n'
    if "req_resp_unique_bytes_ratio" in idx:
        code += '\t{\n'
        code += f'\t\treqUnique := float64(uniqueByteCount(req))\n'
        code += f'\t\trespUnique := features[{idx.get("resp_n_unique_bytes", 5)}]  // resp_n_unique_bytes\n'
        code += f'\t\tif respUnique < 1 {{ respUnique = 1 }}\n'
        code += f'\t\tfeatures[{idx["req_resp_unique_bytes_ratio"]}] = reqUnique / respUnique  // req_resp_unique_bytes_ratio\n'
        code += '\t}\n'
    if "resp_shorter_than_req" in idx:
        code += f'\tif respLen < reqLen {{ features[{idx["resp_shorter_than_req"]}] = 1.0 }} else {{ features[{idx["resp_shorter_than_req"]}] = 0.0 }}  // resp_shorter_than_req\n'

    return code

def main():
    parser = argparse.ArgumentParser(description="Export fingerprint model to Go")
    parser.add_argument("--model-dir", default="fingerprint_model_output")
    parser.add_argument("--output", default=None, help="Output Go file path")
    parser.add_argument("--package", default="fingerprint", help="Go package name")
    parser.add_argument("--member-model-dir", default=None,
                        help="Export per-service implementation RFs to member_models.go")
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")

    if args.member_model_dir:
        export_member_models_go(
            member_model_dir=args.member_model_dir,
            output_path=args.output,
            package_name=args.package,
        )
    else:
        export_go(
            model_dir=args.model_dir,
            output_path=args.output,
            package_name=args.package,
        )

if __name__ == "__main__":
    main()
